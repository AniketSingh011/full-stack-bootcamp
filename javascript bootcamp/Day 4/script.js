// FOR LOOP
console.log("=== FOR LOOP ===");
for (let i = 1; i <= 5; i++) {
    console.log(i);
}

// WHILE LOOP
console.log("=== WHILE LOOP ===");
let j = 1;
while (j <= 5) {
    console.log(j);
    j++;
}

// DO...WHILE LOOP
console.log("=== DO...WHILE LOOP ===");
let k = 1;
do {
    console.log(k);
    k++;
} while (k <= 5);

// Multiplication Table of 5
console.log("=== 5 Times Table ===");
for (let i = 1; i <= 10; i++) {
    console.log(`5 x ${i} = ${5 * i}`);
}